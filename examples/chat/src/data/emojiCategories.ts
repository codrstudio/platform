/**
 * Retorna todos os emojis em uma lista plana
 */
export function getAllEmojis(): string[] {
  return EMOJI_CATEGORIES.flatMap(category => category.emojis)
}

/**
 * Busca emojis por termo (busca no nome da categoria)
 */
export function searchEmojis(term: string): string[] {
  if (!term.trim()) return getAllEmojis()

  const lowerTerm = term.toLowerCase()
  const matchedCategories = EMOJI_CATEGORIES.filter(cat =>
    cat.label.toLowerCase().includes(lowerTerm) ||
    cat.name.toLowerCase().includes(lowerTerm)
  )

  return matchedCategories.flatMap(cat => cat.emojis)
}
